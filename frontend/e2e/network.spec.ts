import { expect, test } from '@playwright/test'
import { setRange } from './controls'

test('independent ECU publication, CAN measurements and saved network playback', async ({page}, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const previous = await (await page.request.get('/api/simulations/current')).json()
  if (previous) {
    await page.getByRole('button', {name: 'Reset · new recording', exact: true}).click()
    await page.getByRole('button', {name: 'Resume', exact: true}).click()
  } else await page.getByRole('button', {name: 'Run demo', exact: true}).click()
  const network = page.getByRole('region', {name: 'ECU network'})
  const speedCard = page.getByTestId('can-speed').locator('..')
  await expect(speedCard).toContainText('FRESH')
  await expect(page.getByTestId('can-temperature')).toContainText('20.')
  await setRange(page.getByRole('slider', {name: 'Brake', exact: true}), 100)
  await page.getByRole('combobox', {name: 'Gear', exact: true}).selectOption('D')
  await expect(page.getByTestId('can-gear')).toHaveText('D')
  await setRange(page.getByRole('slider', {name: 'Throttle', exact: true}), 70)
  await setRange(page.getByRole('slider', {name: 'Brake', exact: true}), 0)
  const canSpeed = async () => Number((await page.getByTestId('can-speed').innerText()).replace(/[^0-9.-]/g, ''))
  await expect.poll(canSpeed).toBeGreaterThan(1)
  await page.getByRole('button', {name: 'Stop ABS/DSC publication'}).click()
  await expect(speedCard).toContainText('TIMEOUT')
  const held = await canSpeed()
  await expect(page.locator('.measurement strong')).toHaveText('FRESH')
  await page.getByRole('button', {name: 'Stop Body publication'}).click()
  await expect(page.getByTestId('can-ignition').locator('..')).toContainText('TIMEOUT')
  await expect.poll(canSpeed).toBe(held)
  await expect(page.getByTestId('can-ignition')).toHaveText('ON')
  await page.getByRole('combobox', {name: 'Gear', exact: true}).selectOption('N')
  // Body's request message cannot arrive while its publication is disabled.
  await expect(page.getByTestId('can-gear')).toHaveText('D')
  await page.getByRole('button', {name: 'Resume Body publication'}).click()
  await expect(page.getByTestId('can-gear')).toHaveText('N')
  await page.getByRole('button', {name: 'Resume ABS/DSC publication'}).click()
  await expect(speedCard).toContainText('FRESH')
  await page.getByRole('button', {name: 'Stop KOMBI publication'}).click()
  await expect(network.locator('.network-source').filter({hasText: 'KOMBI'})).toContainText('TIMEOUT')
  await expect(speedCard).toContainText('FRESH')
  await page.getByRole('textbox', {name: 'Filter CAN ID'}).fill('0x210')
  await expect(page.locator('tbody tr').first()).toContainText('WheelSpeeds')
  await page.screenshot({path: testInfo.outputPath('ecu-network.png'), fullPage: true})
  const id = (await (await page.request.get('/api/simulations/current')).json()).id
  await page.getByRole('button', {name: 'Stop & save', exact: true}).click()
  await expect(page.getByLabel('Saved recording').locator(`option[value="${id}"]`)).toHaveCount(1)
  await page.getByLabel('Saved recording').selectOption(id)
  await page.getByRole('button', {name: 'Load playback', exact: true}).click()
  await expect(page.locator('.mode')).toHaveText('PLAYBACK')
  await expect(page.getByTestId('can-gear')).toHaveText('N')
  for (const button of await network.getByRole('button').all()) await expect(button).toBeDisabled()
  await page.getByRole('button', {name: 'Deterministic rerun', exact: true}).click()
  await expect(page.getByRole('status').filter({hasText: 'Deterministic rerun matched'})).toBeVisible()
  await page.setViewportSize({width: 390, height: 844})
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(errors).toEqual([])
})
