import { expect, test } from '@playwright/test'
import { setRange } from './controls'

test('drive, coast, reject unsafe reverse, brake and replay model speed', async ({page}, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const previous = await (await page.request.get('/api/simulations/current')).json()
  if (previous) {
    await page.getByRole('button', {name: 'Reset · new recording', exact: true}).click()
    await page.getByRole('button', {name: 'Resume', exact: true}).click()
  } else {
    await page.getByRole('button', {name: 'Run demo', exact: true}).click()
  }
  const gear = page.getByRole('combobox', {name: 'Gear', exact: true})
  const brake = page.getByRole('slider', {name: 'Brake', exact: true})
  const speed = async () => Number((await page.getByTestId('physical-speed').innerText()).replace(/[^0-9.-]/g, ''))
  await gear.selectOption('D')
  await expect(page.getByText(/Shift rejected: Press the brake/)).toBeVisible()
  await expect(gear).toHaveValue('P')
  await setRange(brake, 100)
  await gear.selectOption('D')
  await expect(gear).toHaveValue('D')
  await setRange(page.getByRole('slider', {name: 'Throttle', exact: true}), 100)
  await setRange(brake, 0)
  await expect.poll(speed).toBeGreaterThan(3)
  await gear.selectOption('R')
  await expect(page.getByText(/Shift rejected: Stop the vehicle/)).toBeVisible()
  await expect(gear).toHaveValue('D')
  await gear.selectOption('N')
  await expect(gear).toHaveValue('N')
  const coasting = (await (await page.request.get('/api/simulations/current')).json()).state.physical_speed_kph
  await expect.poll(async () => (await (await page.request.get('/api/simulations/current')).json()).state.physical_speed_kph).toBeLessThan(coasting)
  await setRange(brake, 100)
  await expect.poll(speed).toBe(0)
  await gear.selectOption('R')
  await expect(gear).toHaveValue('R')
  await setRange(brake, 0)
  await expect.poll(speed).toBeLessThan(-1)
  await page.getByRole('button', {name: 'Take Engine ECU offline'}).click()
  await expect(page.locator('.measurement strong')).toHaveText('TIMEOUT')
  const reversing = await (await page.request.get('/api/simulations/current')).json()
  await expect.poll(speed).toBeLessThan(-1)
  await page.screenshot({path: testInfo.outputPath('motion-controls.png'), fullPage: true})
  await setRange(brake, 100)
  await expect.poll(speed).toBe(0)
  await page.getByRole('button', {name: 'Bring Engine ECU online'}).click()
  await expect(page.locator('.measurement strong')).toHaveText('FRESH')
  await gear.selectOption('P')
  await expect(gear).toHaveValue('P')
  await page.getByRole('button', {name: 'Stop & save', exact: true}).click()
  await expect(page.getByLabel('Saved recording').locator(`option[value="${reversing.id}"]`)).toHaveCount(1)
  await page.getByLabel('Saved recording').selectOption(reversing.id)
  await page.getByRole('button', {name: 'Load playback', exact: true}).click()
  await expect(page.locator('.mode')).toHaveText('PLAYBACK')
  await expect(gear).toBeDisabled()
  await expect(brake).toBeDisabled()
  const response = page.waitForResponse(r => r.url().endsWith(`/playback?until_ns=${reversing.sim_time_ns}`))
  await setRange(page.getByRole('slider', {name: 'Playback position'}), reversing.sim_time_ns)
  expect((await response).ok()).toBe(true)
  await expect(gear).toHaveValue('R')
  await expect.poll(speed).toBeLessThan(-1)
  await page.getByRole('button', {name: 'Deterministic rerun', exact: true}).click()
  await expect(page.getByRole('status').filter({hasText: 'Deterministic rerun matched'})).toBeVisible()
  await page.setViewportSize({width: 390, height: 844})
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(errors).toEqual([])
})
