import { expect, test } from '@playwright/test'

test('guided ABS demo explains the loss, saves, and opens each playback checkpoint', async ({page}, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const current = await (await page.request.get('/api/simulations/current')).json()
  if (current && !current.stopped) await page.request.post(`/api/simulations/${current.id}/stop`)
  await page.goto('/')
  const guide = page.getByRole('region', {name: 'Guided demo', exact: true})
  await guide.getByRole('button', {name: /Run guided demo/}).click()
  const wheelSpeed = guide.getByLabel('Guided wheel speed', {exact: true})
  const engine = guide.getByLabel('Guided engine RPM', {exact: true})
  await expect(wheelSpeed).toContainText('FRESH')
  await expect(wheelSpeed).toContainText('TIMEOUT', {timeout: 10_000})
  await expect(engine).toContainText('FRESH')
  await expect(guide.getByRole('button', {name: /Inspect outage/})).toBeDisabled()
  await expect(guide.getByText('Signal loss captured. Reception restored.')).toBeVisible({timeout: 20_000})
  await expect(wheelSpeed).toContainText('FRESH')
  await guide.getByRole('button', {name: /Inspect outage/}).click()
  await expect(page.locator('.mode')).toHaveText('PLAYBACK')
  await expect(wheelSpeed).toContainText('TIMEOUT')
  await expect(engine).toContainText('FRESH')
  await expect(guide).toContainText('Recorded CAN observations at 6.00 s')
  await guide.screenshot({path: testInfo.outputPath('guided-outage.png')})
  await guide.getByRole('button', {name: /Before outage/}).click()
  await expect(wheelSpeed).toContainText('FRESH')
  await expect(guide).toContainText('Recorded CAN observations at 2.00 s')
  await guide.getByRole('button', {name: /After recovery/}).click()
  await expect(guide).toContainText('Recorded CAN observations at 10.00 s')
  await expect(wheelSpeed).toContainText('FRESH')
  await page.getByRole('button', {name: 'Deterministic rerun', exact: true}).click()
  await expect(page.getByRole('status').filter({hasText: 'Deterministic rerun matched'})).toBeVisible()
  await page.setViewportSize({width: 390, height: 844})
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await guide.screenshot({path: testInfo.outputPath('guided-recovery-mobile.png')})
  await guide.getByRole('button', {name: 'Back to live controls', exact: true}).click()
  await expect(page.locator('.mode')).toHaveText('LIVE')
  await expect(guide.getByRole('button', {name: /Run guided demo/})).toBeEnabled()
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(errors).toEqual([])
})
