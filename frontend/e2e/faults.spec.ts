import { expect, test } from '@playwright/test'
import { setRange } from './controls'

for (const scenario of ['abs_missing_frames', 'rpm_spike', 'timing_jitter']) {
  test(`scenario ${scenario} runs from UI, exposes effects in playback and reruns`, async ({page}, testInfo) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => {if (message.type() === 'error') errors.push(message.text())})
    const current = await (await page.request.get('/api/simulations/current')).json()
    if (current && !current.stopped) await page.request.post(`/api/simulations/${current.id}/stop`)
    await page.goto('/')
    await expect(page).toHaveTitle(/AutoCAN Studio/)
    await expect(page.getByRole('heading', {name: 'Vehicle lab'})).toBeVisible()
    await page.getByRole('combobox', {name: 'Scenario', exact: true}).selectOption(scenario)
    await page.getByRole('button', {name: 'Run scenario', exact: true}).click()
    const timeline = page.getByRole('region', {name: 'Fault timeline'})
    await expect(timeline.locator('[data-kind="FaultCleared"]').first()).toBeVisible()
    await expect(page.getByRole('button', {name: 'Run demo', exact: true})).toBeEnabled()
    const session = await (await page.request.get('/api/simulations/current')).json()
    expect(session.scenario.id).toBe(scenario)
    expect(session.sim_time_ns).toBe(session.scenario.duration_ns)
    expect(session.stopped).toBe(true)
    await expect(page.getByLabel('Saved recording').locator(`option[value="${session.id}"]`)).toHaveCount(1)
    await page.getByLabel('Saved recording').selectOption(session.id)
    await page.getByRole('button', {name: 'Load playback', exact: true}).click()
    const time = scenario === 'abs_missing_frames' ? 400_000_000 : 150_000_000
    await setRange(page.getByRole('slider', {name: 'Playback position'}), time)
    const active = page.getByLabel('Active faults', {exact: true})
    if (scenario === 'abs_missing_frames') {
      await expect(page.getByTestId('can-speed').locator('..')).toContainText('TIMEOUT')
      await expect(active).toContainText('abs-missing')
    } else if (scenario === 'rpm_spike') {
      await expect(page.locator('.rpm-value')).toContainText('7,000')
      await expect(active).toContainText('rpm-spike')
      await expect(timeline.locator('[data-kind="FaultCleared"]')).toHaveCount(0)
      await page.getByRole('region', {name: 'Scenarios and faults'}).screenshot({path: testInfo.outputPath('fault-lab.png')})
      await page.screenshot({path: testInfo.outputPath('m6-fault-scenarios.png'), fullPage: true})
    } else {
      await expect(active).toContainText('engine-frequency')
      await expect(active).toContainText('engine-jitter')
      expect(session.frames.some((f: {can_id: number; sim_time_ns: number; created_at_ns: number}) =>
        f.can_id === 512 && f.sim_time_ns !== f.created_at_ns)).toBe(true)
      await page.getByRole('textbox', {name: 'Filter CAN ID'}).fill('0x200')
      await expect(page.getByRole('columnheader', {name: 'DELAY / ms', exact: true})).toBeVisible()
      await expect(page.locator('tbody tr').first()).toContainText('24.942')
    }
    await expect(page.getByRole('button', {name: 'Inject fault'})).toBeDisabled()
    await expect(page.getByRole('button', {name: 'Run scenario', exact: true})).toBeDisabled()
    await page.getByRole('button', {name: 'Deterministic rerun', exact: true}).click()
    await expect(page.getByRole('status').filter({hasText: 'Deterministic rerun matched'})).toBeVisible()
    await page.setViewportSize({width: 390, height: 844})
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
    await page.getByRole('region', {name: 'Scenarios and faults'}).screenshot({path: testInfo.outputPath('fault-lab-mobile.png')})
    await expect(page.getByRole('alert')).toHaveCount(0)
    expect(errors).toEqual([])
  })
}

test('manual fault parameters, paused injection, reconnect, clear and recorded timeline', async ({page}) => {
  const current = await (await page.request.get('/api/simulations/current')).json()
  if (current && !current.stopped) await page.request.post(`/api/simulations/${current.id}/stop`)
  await page.goto('/')
  await page.getByRole('button', {name: 'Run demo', exact: true}).click()
  await page.getByRole('button', {name: 'Pause', exact: true}).click()
  await page.getByRole('textbox', {name: 'Fault ID', exact: true}).fill('browser-spike')
  await page.getByRole('spinbutton', {name: 'Value (rpm)'}).fill('6500')
  await page.getByRole('button', {name: 'Inject fault'}).click()
  const active = page.getByLabel('Active faults', {exact: true})
  await expect(active).toContainText('No active library faults')
  await page.getByRole('button', {name: 'Resume', exact: true}).click()
  await expect(active).toContainText('browser-spike')
  await expect(page.locator('.rpm-value')).toContainText('6,500')
  await page.getByRole('button', {name: 'Pause', exact: true}).click()
  await page.reload()
  await expect(active).toContainText('browser-spike')
  await expect(page.getByRole('region', {name: 'Fault timeline'})).toContainText('Fault activated')
  await page.getByRole('button', {name: 'Clear browser-spike', exact: true}).click()
  await expect(active).toContainText('browser-spike')
  await page.getByRole('button', {name: 'Resume', exact: true}).click()
  await expect(active).toContainText('No active library faults')
  await expect(page.locator('.rpm-value')).toContainText('800')
  const session = await (await page.request.get('/api/simulations/current')).json()
  await page.getByRole('button', {name: 'Stop & save', exact: true}).click()
  await expect(page.getByLabel('Saved recording').locator(`option[value="${session.id}"]`)).toHaveCount(1)
  await page.getByLabel('Saved recording').selectOption(session.id)
  await page.getByRole('button', {name: 'Deterministic rerun', exact: true}).click()
  await expect(page.getByRole('status').filter({hasText: 'Deterministic rerun matched'})).toBeVisible()
  await page.getByRole('button', {name: 'Reset · new recording', exact: true}).click()
  await expect(page.getByRole('region', {name: 'Fault timeline'})).not.toContainText('browser-spike')
  await expect(page.getByRole('alert')).toHaveCount(0)
})
